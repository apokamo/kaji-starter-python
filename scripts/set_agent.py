#!/usr/bin/env python3
"""workflow YAML の agent / model / effort を指定 CLI へ一括変換する。

Usage:
    uv run python scripts/set_agent.py <cli>    # cli: claude | codex | gemini

kaji v0.17.0 以降、`.kaji/wf/official/**` は kaji が所有し、下流リポジトリは直接編集しない
（kaji の更新で変更が失われるか衝突する）。本 script はその所有権契約に従って動く。

- `.kaji/wf/official/**` は読み取り専用。変換が必要な場合だけ
  `.kaji/wf/custom/<category>/<stem>-<cli>.yaml` へ派生を生成し、`name:` を新しい filename
  stem に合わせる（契約が定める「custom へコピーして編集する」手順の自動化）。official が
  既に指定 CLI と一致していれば派生を作らない
- `.kaji/wf/custom/**` は利用者所有なのでその場で書き換える。ただし stem が別 CLI 名で
  終わるファイル（他 CLI 向けの変種）は対象外
- 生成した派生の先頭には generated header を付ける。同名ファイルに header が無い場合は
  利用者の手動管理とみなし、派生の生成も in-place 変換も行わない（手で編集した custom を
  一切書き換えない）

変換自体は行単位置換でコメント・構造を保持し、同じ CLI 指定で再実行しても差分ゼロ（冪等）。

- model は step の役割 tier（heavy / light）で決まる。effort は workflow ごとの
  チューニング値（dev-thorough の xhigh 等）なので、対象 CLI で無効な値でない限り
  変更しない
- CLI 間の model / effort 対応表は本 script 内が正本。ガイドの表はここから転記する
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

WF_DIR = Path(".kaji/wf")
OFFICIAL_SUBDIR = "official"
CUSTOM_SUBDIR = "custom"

# 生成した派生ファイルの先頭に置く目印。手動管理へ移す場合は利用者がこの行を削除する。
GENERATED_MARK = "# GENERATED by scripts/set_agent.py"

# CLI → tier → model の対応表（正本）
MODEL_MAP: dict[str, dict[str, str]] = {
    "claude": {"heavy": "opus", "light": "sonnet"},
    "codex": {"heavy": "gpt-5.5", "light": "gpt-5.5"},
    "gemini": {"heavy": "gemini-3-pro", "light": "gemini-3-flash"},
}

# CLI ごとの effort 許容値。無効値を検出したら対応表で置換する
EFFORT_ALLOWED: dict[str, set[str]] = {
    "claude": {"low", "medium", "high", "xhigh", "max"},
    "codex": {"none", "minimal", "low", "medium", "high", "xhigh"},
    "gemini": {"low", "medium", "high", "xhigh"},
}
EFFORT_FALLBACK: dict[str, dict[str, str]] = {
    "codex": {"max": "xhigh"},
    "gemini": {"max": "xhigh", "none": "low", "minimal": "low"},
}

# 軽量級 step（それ以外は heavy 扱い。未知の step id も heavy に倒す）
LIGHT_STEPS: set[str] = {"start", "pr", "close"}

STEP_ID_RE = re.compile(r"^  - id: (\S+)\s*$")
AGENT_RE = re.compile(r"^    agent: (\S+)\s*$")
MODEL_RE = re.compile(r"^    model: (\S+)\s*$")
EFFORT_RE = re.compile(r"^    effort: (\S+)\s*$")
# step 直下の agent/model/effort 行のうち正規形に一致しないもの（inline comment 等）を
# 検出するための緩いパターン。silent skip を避け fail-loud にするために使う。
LOOSE_FIELD_RE = re.compile(r"^    (agent|model|effort):")
NAME_RE = re.compile(r"^name: (\S+)\s*$")


@dataclass(frozen=True)
class Write:
    """1 ファイル分の書き込み計画。"""

    path: Path
    content: str
    steps: int
    source: Path | None  # official 由来の派生なら変換元。None は custom の in-place 変換


def tier_of(step_id: str) -> str:
    return "light" if step_id in LIGHT_STEPS else "heavy"


def convert_text(text: str, cli: str, label: str) -> tuple[str, int, list[str]]:
    """1 ファイル分の内容を変換し、(新しい内容, 書き換えた step 数, エラーリスト) を返す。"""
    lines = text.splitlines(keepends=True)
    out: list[str] = []
    errors: list[str] = []
    changed_steps: set[str] = set()
    current_step = ""

    for lineno, line in enumerate(lines, start=1):
        stripped = line.rstrip("\n")
        if m := STEP_ID_RE.match(stripped):
            current_step = m.group(1)
        elif m := AGENT_RE.match(stripped):
            value = m.group(1)
            if value not in MODEL_MAP:
                errors.append(f"{label}:{lineno}: 想定外の agent 値 '{value}'")
            elif value != cli:
                line = f"    agent: {cli}\n"
                changed_steps.add(current_step)
        elif m := MODEL_RE.match(stripped):
            target = MODEL_MAP[cli][tier_of(current_step)]
            if m.group(1) != target:
                line = f"    model: {target}\n"
                changed_steps.add(current_step)
        elif m := EFFORT_RE.match(stripped):
            value = m.group(1)
            if value not in EFFORT_ALLOWED[cli]:
                replacement = EFFORT_FALLBACK.get(cli, {}).get(value)
                if replacement is None:
                    errors.append(f"{label}:{lineno}: effort '{value}' は {cli} で無効")
                else:
                    line = f"    effort: {replacement}\n"
                    changed_steps.add(current_step)
        elif m := LOOSE_FIELD_RE.match(stripped):
            # 正規形に一致しない agent/model/effort 行（例: inline comment 付き）は
            # silent skip すると agent だけ変換され model/effort が取り残された壊れた
            # 組を生む。fail-loud にして対象を明示する。
            errors.append(
                f"{label}:{lineno}: 想定パターン外の {m.group(1)} 行"
                f"（正規形 '    {m.group(1)}: <value>' でない）: {stripped!r}"
            )
        out.append(line)

    return "".join(out), len(changed_steps), errors


def rename_workflow(text: str, new_stem: str, label: str) -> tuple[str, list[str]]:
    """top-level `name:` を新しい filename stem に合わせる（name == stem が kaji の不変条件）。"""
    lines = text.splitlines(keepends=True)
    for i, line in enumerate(lines):
        if NAME_RE.match(line.rstrip("\n")):
            lines[i] = f"name: {new_stem}\n"
            return "".join(lines), []
    return text, [f"{label}: top-level 'name:' 行が見つからない（派生を生成できない）"]


def generated_header(source: Path, cli: str) -> str:
    return (
        f"{GENERATED_MARK} (source: {source.as_posix()}, cli={cli})\n"
        f"# {source.as_posix()} は kaji 所有のため直接編集しない。この派生を手で編集しても\n"
        f"# 次回実行で再生成される。手動管理へ移す場合は上の GENERATED 行を削除する。\n"
    )


def derived_path(source: Path, wf_dir: Path, cli: str) -> Path:
    """official YAML に対応する custom 派生の path。category は stem の先頭 token。"""
    stem = source.stem
    category = stem.split("-")[0]
    return wf_dir / CUSTOM_SUBDIR / category / f"{stem}-{cli}.yaml"


def is_other_cli_variant(stem: str, cli: str) -> bool:
    """stem が対象外 CLI 名で終わる（他 CLI 向けの変種である）か。"""
    return any(stem.endswith(f"-{other}") for other in MODEL_MAP if other != cli)


def plan_conversions(wf_dir: Path, cli: str) -> tuple[list[Write], list[str], list[str]]:
    """(書き込み計画, エラー, 通知) を返す。この関数はファイルを書き換えない。"""
    writes: list[Write] = []
    errors: list[str] = []
    notices: list[str] = []
    # 手動管理と判定した派生先。official loop で skip するだけでは下の custom loop が
    # 同じ path を「利用者所有の custom」として拾い直し in-place 変換してしまうため、
    # ここに記録して custom loop からも除外する（skip 宣言と実挙動を一致させる）。
    manual_paths: set[Path] = set()

    for path in sorted((wf_dir / OFFICIAL_SUBDIR).rglob("*.yaml")):
        text = path.read_text(encoding="utf-8")
        converted, steps, file_errors = convert_text(text, cli, str(path))
        errors.extend(file_errors)
        if converted == text:
            notices.append(f"{path}: 既に agent={cli} 構成のため派生を作らない（read-only）")
            continue

        target = derived_path(path, wf_dir, cli)
        renamed, rename_errors = rename_workflow(converted, target.stem, str(path))
        if rename_errors:
            errors.extend(rename_errors)
            continue
        if target.exists() and not target.read_text(encoding="utf-8").startswith(GENERATED_MARK):
            manual_paths.add(target)
            notices.append(
                f"{target}: generated header が無い（手動管理）ため一切書き換えない。"
                f"{path} の変換結果は反映していない"
            )
            continue
        writes.append(Write(target, generated_header(path, cli) + renamed, steps, path))

    for path in sorted((wf_dir / CUSTOM_SUBDIR).rglob("*.yaml")):
        text = path.read_text(encoding="utf-8")
        if text.startswith(GENERATED_MARK):
            # official 由来の生成物。上の loop で変換元から再生成する
            continue
        if path in manual_paths:
            # official 由来の派生先と衝突する手動管理ファイル。notice は official loop で
            # 出済みなので、ここでは write plan に載せないことだけを保証する
            continue
        if is_other_cli_variant(path.stem, cli):
            notices.append(f"{path}: 別 CLI 向けの変種のため対象外")
            continue
        converted, steps, file_errors = convert_text(text, cli, str(path))
        errors.extend(file_errors)
        writes.append(Write(path, converted, steps, None))

    return writes, errors, notices


def main() -> int:
    args = sys.argv[1:]
    if len(args) != 1 or args[0] not in MODEL_MAP:
        known = " | ".join(MODEL_MAP)
        print(f"usage: python scripts/set_agent.py <{known}>", file=sys.stderr)
        return 2

    cli = args[0]
    if not sorted(WF_DIR.rglob("*.yaml")):
        print(f"error: {WF_DIR}/**/*.yaml が見つからない", file=sys.stderr)
        return 1

    # Phase 1: 全ファイルを変換（メモリ上）。1 つでもエラーがあれば書き込まない。
    writes, errors, notices = plan_conversions(WF_DIR, cli)

    if errors:
        print("変換エラー（どのファイルも書き換えていない）:", file=sys.stderr)
        for err in errors:
            print(f"  {err}", file=sys.stderr)
        return 1

    # Phase 2: エラーが無い場合のみ一括 write（atomic: 途中失敗による混在を防ぐ）。
    written = 0
    total_steps = 0
    for item in writes:
        origin = f"{item.source} -> " if item.source else ""
        if item.path.exists() and item.path.read_text(encoding="utf-8") == item.content:
            # 既に同内容（再実行）。mtime を動かさないため書き込まない
            print(f"{origin}{item.path}: no change")
            continue
        item.path.parent.mkdir(parents=True, exist_ok=True)
        item.path.write_text(item.content, encoding="utf-8")
        written += 1
        total_steps += item.steps
        suffix = " (generated)" if item.source else ""
        print(f"{origin}{item.path}: {item.steps} steps updated{suffix}")

    for notice in notices:
        print(f"note: {notice}")

    print(
        f"\n{len(writes)} files planned, {written} written, {total_steps} steps updated "
        f"(agent={cli})。{WF_DIR}/{OFFICIAL_SUBDIR}/ は kaji 所有のため書き換えない"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
